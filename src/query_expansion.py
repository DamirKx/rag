_COMPILED = [(re.compile(pattern), terms) for pattern, terms in RULES]


def legal_terms(question: str) -> List[str]:
    """Термины закона, подходящие к вопросу (без повторов, в порядке правил)."""
    text = question.lower().replace("ё", "е")
    found: List[str] = []
    for pattern, terms in _COMPILED:
        if pattern.search(text) and terms not in found:
            found.append(terms)
    return found


def expand_query(question: str) -> str:
    """Вопрос с дописанными терминами закона; если правил не нашлось — вопрос как есть."""
    terms = legal_terms(question)
    return f"{question} ({'; '.join(terms)})" if terms else question
